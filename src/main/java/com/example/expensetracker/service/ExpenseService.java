package com.example.expensetracker.service;

import com.example.expensetracker.dto.TotalResponse;
import com.example.expensetracker.exception.ResourceNotFoundException;
import com.example.expensetracker.model.Expense;
import com.example.expensetracker.repository.ExpenseRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.List;

/**
 * Service class handling business logic for Expense operations.
 */
@Service
public class ExpenseService {

    private final ExpenseRepository expenseRepository;

    @Autowired
    public ExpenseService(ExpenseRepository expenseRepository) {
        this.expenseRepository = expenseRepository;
    }

    /**
     * Retrieve all expenses, optionally filtered by category.
     *
     * @param category category filter (optional, 'All' returns all)
     * @return list of expenses sorted by date descending
     */
    public List<Expense> getExpenses(String category) {
        if (category == null || category.trim().isEmpty() || category.equalsIgnoreCase("All")) {
            return expenseRepository.findAllByOrderByDateDesc();
        }
        return expenseRepository.findByCategoryIgnoreCaseOrderByDateDesc(category.trim());
    }

    /**
     * Retrieve a single expense by its MongoDB ID.
     *
     * @param id MongoDB ObjectId string
     * @return found Expense
     * @throws ResourceNotFoundException if no expense matches the given id
     */
    public Expense getExpenseById(String id) {
        return expenseRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Expense not found with id: " + id));
    }

    /**
     * Create and persist a new expense.
     *
     * @param expense expense details
     * @return saved Expense
     */
    public Expense createExpense(Expense expense) {
        // Ensure id is generated by MongoDB on creation
        expense.setId(null);
        // Normalize title & category
        expense.setTitle(expense.getTitle().trim());
        expense.setCategory(capitalize(expense.getCategory().trim()));
        if (expense.getAmount() != null) {
            expense.setAmount(expense.getAmount().setScale(2, RoundingMode.HALF_UP));
        }
        return expenseRepository.save(expense);
    }

    /**
     * Update an existing expense by ID.
     *
     * @param id             MongoDB ObjectId string
     * @param expenseDetails updated expense values
     * @return updated Expense
     * @throws ResourceNotFoundException if expense does not exist
     */
    public Expense updateExpense(String id, Expense expenseDetails) {
        Expense existingExpense = getExpenseById(id);

        existingExpense.setTitle(expenseDetails.getTitle().trim());
        existingExpense.setAmount(expenseDetails.getAmount().setScale(2, RoundingMode.HALF_UP));
        existingExpense.setCategory(capitalize(expenseDetails.getCategory().trim()));
        existingExpense.setDate(expenseDetails.getDate());

        return expenseRepository.save(existingExpense);
    }

    /**
     * Delete an expense by ID.
     *
     * @param id MongoDB ObjectId string
     * @throws ResourceNotFoundException if expense does not exist
     */
    public void deleteExpense(String id) {
        Expense existingExpense = getExpenseById(id);
        expenseRepository.delete(existingExpense);
    }

    /**
     * Calculate total spent across all or filtered expenses.
     *
     * @param category category filter (optional)
     * @return TotalResponse containing total amount, category label, and count
     */
    public TotalResponse calculateTotal(String category) {
        List<Expense> expenses = getExpenses(category);

        BigDecimal total = expenses.stream()
                .map(Expense::getAmount)
                .filter(amount -> amount != null)
                .reduce(BigDecimal.ZERO, BigDecimal::add)
                .setScale(2, RoundingMode.HALF_UP);

        String activeCategory = (category == null || category.trim().isEmpty() || category.equalsIgnoreCase("All"))
                ? "All"
                : capitalize(category.trim());

        return new TotalResponse(activeCategory, total, expenses.size());
    }

    private String capitalize(String str) {
        if (str == null || str.isEmpty()) {
            return str;
        }
        return str.substring(0, 1).toUpperCase() + str.substring(1).toLowerCase();
    }
}
